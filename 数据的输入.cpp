#include<iostream>
#include<string>
using namespace std;

int main()
{
	 
	//1.整形 
	
	int a=0;
	cout<<"请给变量a赋值；"<<endl;
	cin>>a;
	cout<<"整形变量a为；"<< a << endl;
	
	//2.浮点型 
	float b=3.14f;
	cout<<"请给变量b赋值："<<endl;
	cin>>b;
	cout<<"浮点型变量b="<<b<<endl;
	
	
	//3.字符型 
	string c="";
	cout<<"请给变量c赋值："<<endl;
	cin>>c;
	cout<<"c="<<c<<endl;
	char d=0;
	cout<<"d?"<<endl;
	cin>>d;
	cout<<"d="<<d<<endl;
	
	//3.bool 类型
	bool e=0; 
	cout<<"e?"<<endl;
	cin>>e;
	cout<<"e="<<e<<endl;
	
	
	
	
	
	
	
	
	system("pause");
	return 0;
	
	
}






